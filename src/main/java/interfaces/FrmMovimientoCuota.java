    private void txtCodCuotaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtCodCuotaActionPerformed
        String idCuota = txtCodCuota.getText().trim();
        if (idCuota.isEmpty()) return;

        File fEncabezado = new File("encabezado_cuota.txt");
        boolean encontrado = false;
        boolean statusCuota = false;
        String idClienteGuardado = "";

        if (fEncabezado.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(fEncabezado))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos[0].trim().equals(idCuota)) {
                        encontrado = true;
                        idClienteGuardado = datos[2].trim();
                        statusCuota = Boolean.parseBoolean(datos[4].trim());
                        break;
                    }
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error leyendo encabezado: " + e.getMessage());
            }
        }

        if (encontrado) {
            if (!statusCuota) {
                JOptionPane.showMessageDialog(this, "Modificando", "Aviso", JOptionPane.INFORMATION_MESSAGE);
                esNuevaCuota = false;
                txtCodCliente.setEnabled(true);
                txtCodCliente.setText(idClienteGuardado);
                btnProcesar.setEnabled(true);
                txtCodCuota.setEnabled(false);
                txtCodCliente.requestFocus();
                // Disparar la búsqueda del cliente automáticamente
                txtCodClienteActionPerformed(null); 
            } else {
                JOptionPane.showMessageDialog(this, "Esta cuota ya fue procesada/actualizada. No se puede modificar.", "Error", JOptionPane.ERROR_MESSAGE);
                aplicarEstadoInicial();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Creando", "Aviso", JOptionPane.INFORMATION_MESSAGE);
            esNuevaCuota = true;
            txtCodCliente.setEnabled(true);
            btnProcesar.setEnabled(true);
            txtCodCuota.setEnabled(false);
            txtCodCliente.requestFocus();
        }
    }//GEN-LAST:event_txtCodCuotaActionPerformed

