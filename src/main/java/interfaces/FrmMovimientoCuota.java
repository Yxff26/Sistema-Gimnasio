    private List<String> leerArchivo(String ruta) {
        List<String> lineas = new ArrayList<>();
        File f = new File(ruta);
        if (!f.exists()) return lineas;

        try (BufferedReader br = new BufferedReader(new FileReader(f))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                lineas.add(linea);
            }
        } catch (IOException e) {
            System.out.println("Error leyendo " + ruta);
        }
        return lineas;
    }

    private void escribirArchivo(String ruta, List<String> lineas) throws IOException {
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(ruta, false))) {
            for (String linea : lineas) {
                bw.write(linea);
                bw.newLine();
            }
        }
    }

