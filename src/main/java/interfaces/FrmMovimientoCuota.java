    private void txtCodClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtCodClienteActionPerformed
        String idCliente = txtCodCliente.getText().trim();
        if (idCliente.isEmpty()) return;

        // 1. Validar Cliente (Socio y Activo) y obtener Nombre y Balance
        boolean clienteValido = false;
        String nombreCompleto = "";
        String balanceCliente = "0.0";

        try (BufferedReader br = new BufferedReader(new FileReader("clientes.txt"))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                String[] datos = linea.split(",", -1);
                if (datos.length >= 13 && datos[0].trim().equals(idCliente)) {
                    // Ajustamos los índices basados en la estructura real del archivo
                    String estado = datos[9].trim();
                    String tipo = datos[10].trim(); 

                    // Usamos .contains para manejar "Socio Activo"
                    if (tipo.toLowerCase().contains("socio") && estado.equalsIgnoreCase("Activo")) {
                        clienteValido = true;
                        String nombre = datos[1].trim();
                        String apellido1 = datos[2].trim();
                        String apellido2 = datos[3].trim();
                        nombreCompleto = nombre + " " + apellido1 + " " + apellido2;

                        // El balance está en la posición 12
                        balanceCliente = datos[12].trim();
                        break;
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error leyendo archivo de clientes: " + e.getMessage());
            return;
        }

        if (!clienteValido) {
            JOptionPane.showMessageDialog(this, "Error: El cliente no existe, no es Socio o no está Activo.", "Validación", JOptionPane.ERROR_MESSAGE);
            txtCodCliente.setText("");
            txtNombre.setText("");
            txtTotalPendiente.setText("0.0");
            modeloTabla.setRowCount(0);
            txtTotalCuota.setText("0.0");
            txtTotalCuota.setEnabled(false); // <-- ¡NUEVO CAMBIO AQUÍ! (Mantenemos bloqueado si falla)
            return;
        }

        // Asignar valores encontrados a los campos correspondientes
        txtNombre.setText(nombreCompleto);
        txtTotalPendiente.setText(balanceCliente);

        // 2. Extraer los cobros de cobros.txt y llenar la tabla exactamente con las 5 columnas del diseño
        modeloTabla.setRowCount(0);
        double totalCuota = 0.0;
        String idCuotaActual = txtCodCuota.getText().trim();

        File fCobros = new File("cobros.txt");
        if (fCobros.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(fCobros))) {
                String linea;
                int seccion = 1;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);

                    // Estructura cobros.txt: 0:Id_Cobro, 1:Fecha, 2:Id_Cliente, 3:Valor, 4:Concepto, 5:Status
                    if (datos.length >= 6 && datos[2].trim().equals(idCliente)) {
                        boolean statusCobro = Boolean.parseBoolean(datos[5].trim());
                        double valorCobro = Double.parseDouble(datos[3].trim());

                        // Solo traer los cobros pendientes (false) y con valor > 0
                        if (!statusCobro && valorCobro > 0) {
                            String idCobro = datos[0].trim();
                            String concepto = datos[4].trim();

                            // Columnas exactas de la tabla: Id Cuota, Sección, Concepto, Valor Cuota, Id Cobro
                            modeloTabla.addRow(new Object[]{idCuotaActual, seccion, concepto, valorCobro, idCobro});
                            totalCuota += valorCobro;
                            seccion++;
                        }
                    }
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error leyendo el archivo de cobros: " + e.getMessage());
            }
        }

        txtTotalCuota.setText(String.valueOf(totalCuota));

        if (modeloTabla.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "El socio no tiene cobros pendientes.", "Información", JOptionPane.INFORMATION_MESSAGE);
            btnProcesar.setEnabled(false);
            txtTotalCuota.setEnabled(false); // <-- ¡NUEVO CAMBIO AQUÍ! (Bloqueamos si no hay deudas)
        } else {
            btnProcesar.setEnabled(true);
            txtTotalCuota.setEnabled(true);  // <-- ¡NUEVO CAMBIO AQUÍ! (Activamos para recibir el abono)
            txtTotalCuota.requestFocus();    // <-- ¡NUEVO CAMBIO AQUÍ! (Opcional: Mandamos el cursor de texto directo a este input por comodidad)
        }
    }//GEN-LAST:event_txtCodClienteActionPerformed

