    private void txtIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdActionPerformed
        String idStr = txtId.getText().trim();
        if (idStr.isEmpty()) {
            setCamposHabilitados(false);
            return;
        }

        // Validar que el ID sea un número entero (Requisito de la tabla)
        try {
            Integer.parseInt(idStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID del Estado de Reserva debe ser un número entero.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtId.setText("");
            setCamposHabilitados(false);
            txtId.requestFocus();
            return;
        }

        File archivo = new File("estados_reserva.txt");
        boolean encontrado = false;
        String estadoDesc = "", estadoLogico = "1";

        if (archivo.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length >= 2 && datos[0].trim().equals(idStr)) {
                        encontrado = true;
                        estadoDesc = datos[1].trim();
                        // Si existe una tercera posición, es el estado lógico, sino asumimos 1
                        estadoLogico = datos.length > 2 ? datos[2].trim() : "1"; 
                        break;
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al buscar el estado de reserva: " + e.getMessage());
            }
        }

        if (!encontrado) {
            JOptionPane.showMessageDialog(this, "Creando...", "Aviso", JOptionPane.INFORMATION_MESSAGE);
            esNuevoEstadoReserva = true;

            // Habilitar campos y botones para nuevo registro
            setCamposHabilitados(true);
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(false);

            txtEstado.requestFocus();
        } else {
            if (estadoLogico.equals("0")) {
                JOptionPane.showMessageDialog(this, "Este estado de reserva se encuentra ELIMINADO/INACTIVO.\nNo es posible modificarlo.", "Inactivo", JOptionPane.ERROR_MESSAGE);
                limpiarCampos();
                return;
            }

            JOptionPane.showMessageDialog(this, "Modificando...", "Aviso", JOptionPane.WARNING_MESSAGE);
            esNuevoEstadoReserva = false;

            txtEstado.setText(estadoDesc);

            // Habilitar campos y botones para modificación
            setCamposHabilitados(true);
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(true);

            txtEstado.requestFocus();
        }
    }//GEN-LAST:event_txtIdActionPerformed

