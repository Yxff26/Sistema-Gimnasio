    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String idStr = txtId.getText().trim();
        String estadoDesc = txtEstado.getText().trim();

        // 1. Validar campos obligatorios
        if (idStr.isEmpty() || estadoDesc.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Los campos ID y Estado son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        File archivo = new File("estados_reserva.txt");
        List<String> lineasArchivo = new ArrayList<>();

        if (archivo.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                        if (!esNuevoEstadoReserva) {
                            // Actualiza y mantiene el estado 1 (Activo)
                            lineasArchivo.add(idStr + "," + estadoDesc + ",1");
                        }
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo: " + e.getMessage());
            }
        }

        if (esNuevoEstadoReserva) {
            // Evitar duplicados si por error se intenta guardar uno nuevo que ya existía (incluso borrado)
            for (String l : lineasArchivo) {
                String[] datos = l.split(",", -1);
                if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                    JOptionPane.showMessageDialog(this, "El ID de este estado de reserva ya existe en el sistema.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
            // Agrega nuevo con estado 1
            lineasArchivo.add(idStr + "," + estadoDesc + ",1");
        }

        try (PrintWriter pw = new PrintWriter(new FileWriter(archivo))) {
            for (String l : lineasArchivo) {
                pw.println(l);
            }
            JOptionPane.showMessageDialog(this, "Datos guardados correctamente.");
            limpiarCampos();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

