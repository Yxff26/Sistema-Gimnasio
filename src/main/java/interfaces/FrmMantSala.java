    private void txtIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdActionPerformed
        String idStr = txtId.getText().trim();
        if (idStr.isEmpty()) {
            setCamposHabilitados(false);
            return;
        }

        // Validar que el ID sea un número entero
        try {
            Integer.parseInt(idStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de la Sala debe ser un número entero.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtId.setText("");
            txtId.requestFocus();
            setCamposHabilitados(false);
            return;
        }

        java.io.File archivo = new java.io.File("salas.txt");
        boolean encontrado = false;
        String nombre = "", descripcion = "", idLocalizacion = "", estado = "1";

        if (archivo.exists()) {
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    // Estructura: Id_Sala, Nombre, Descripcion, Id_Localizacion, Estado
                    if (datos.length >= 4 && datos[0].trim().equals(idStr)) {
                        encontrado = true;
                        nombre = datos[1].trim();
                        descripcion = datos[2].trim();
                        idLocalizacion = datos[3].trim();
                        estado = datos.length > 4 ? datos[4].trim() : "1";
                        break;
                    }
                }
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al buscar la sala: " + e.getMessage());
            }
        }

        if (!encontrado) {
            JOptionPane.showMessageDialog(this, "Creando nueva sala...", "Aviso", JOptionPane.INFORMATION_MESSAGE);
            esNuevaSala = true;

            // Desbloquear campos para escritura
            setCamposHabilitados(true);
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(false);

            txtNombre.requestFocus();
        } else {
            if (estado.equals("0")) {
                JOptionPane.showMessageDialog(this, "Esta sala se encuentra ELIMINADA/INACTIVA.\nNo es posible modificarla.", "Inactivo", JOptionPane.ERROR_MESSAGE);
                limpiarCampos();
                return;
            }

            JOptionPane.showMessageDialog(this, "Modificando sala existente...", "Aviso", JOptionPane.WARNING_MESSAGE);
            esNuevaSala = false;

            txtNombre.setText(nombre);
            txtDescripcion.setText(descripcion);
            txtIdLocalizacion.setText(idLocalizacion);

            // Desbloquear campos para edición
            setCamposHabilitados(true);
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(true);

            txtNombre.requestFocus();
        }
    }//GEN-LAST:event_txtIdActionPerformed

