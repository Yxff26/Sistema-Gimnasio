    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String idStr = txtId.getText().trim();
        String nombre = txtNombre.getText().trim();
        String descripcion = txtDescripcion.getText().trim();
        String idLocStr = txtIdLocalizacion.getText().trim();

        // 1. Validar atributos obligatorios
        if (idStr.isEmpty() || nombre.isEmpty() || descripcion.isEmpty() || idLocStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Integer.parseInt(idLocStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de Localización debe ser un número entero válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtIdLocalizacion.requestFocus();
            return;
        }

        // 2. VALIDAR QUE EL ID DE LOCALIZACIÓN EXISTA EN SU ARCHIVO
        java.io.File archivoLocalizaciones = new java.io.File("localizaciones.txt");
        boolean localizacionExiste = false;

        if (archivoLocalizaciones.exists()) {
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivoLocalizaciones))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    // Asumiendo que localizaciones guarda: Id_Localizacion, Tipo, Estado(opcional)
                    if (datos.length > 0 && datos[0].trim().equals(idLocStr)) {
                        String estadoLoc = datos.length > 2 ? datos[2].trim() : "1";
                        if (estadoLoc.equals("1")) {
                            localizacionExiste = true;
                            break;
                        }
                    }
                }
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al verificar la localización: " + e.getMessage());
                return;
            }
        }

        if (!localizacionExiste) {
            JOptionPane.showMessageDialog(this, "El ID de Localización especificado NO existe o se encuentra inactivo en el sistema.", "Error de Referencia", JOptionPane.ERROR_MESSAGE);
            txtIdLocalizacion.requestFocus();
            return;
        }

        // 3. Guardar en salas.txt
        java.io.File archivo = new java.io.File("salas.txt");
        java.util.List<String> lineasArchivo = new java.util.ArrayList<>();

        if (archivo.exists()) {
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                        if (!esNuevaSala) {
                            // Actualiza manteniendo el estado activo (1)
                            lineasArchivo.add(idStr + "," + nombre + "," + descripcion + "," + idLocStr + ",1");
                        }
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo de salas: " + e.getMessage());
            }
        }

        if (esNuevaSala) {
            for (String l : lineasArchivo) {
                String[] datos = l.split(",", -1);
                if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                    JOptionPane.showMessageDialog(this, "El ID de esta sala ya existe.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
            // Agrega nueva sala con estado activo (1)
            lineasArchivo.add(idStr + "," + nombre + "," + descripcion + "," + idLocStr + ",1");
        }

        try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter(archivo))) {
            for (String l : lineasArchivo) {
                pw.println(l);
            }
            JOptionPane.showMessageDialog(this, "Sala guardada correctamente.");
            limpiarCampos();
        } catch (java.io.IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar sala: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String idStr = txtId.getText().trim();
        if (idStr.isEmpty()) return;

        int confirm = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar la sala ID: " + idStr + "?", "Confirmar", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        java.io.File archivo = new java.io.File("salas.txt");
        java.util.List<String> lineasArchivo = new java.util.ArrayList<>();
        boolean encontrado = false;

        if (archivo.exists()) {
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                        String nom = datos.length > 1 ? datos[1].trim() : "";
                        String desc = datos.length > 2 ? datos[2].trim() : "";
                        String idLoc = datos.length > 3 ? datos[3].trim() : "";
                        // Cambiar estado a inactivo (0)
                        lineasArchivo.add(idStr + "," + nom + "," + desc + "," + idLoc + ",0");
                        encontrado = true;
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo: " + e.getMessage());
                return;
            }
        }

        if (encontrado) {
            try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter(archivo))) {
                for (String l : lineasArchivo) {
                    pw.println(l);
                }
                JOptionPane.showMessageDialog(this, "Sala eliminada lógicamente.");
                limpiarCampos();
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

