    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String idStr = txtId.getText().trim();
        if (idStr.isEmpty()) return;

        int confirm = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar al entrenador ID: " + idStr + "?", "Confirmar", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        java.io.File archivo = new java.io.File("entrenadores.txt");
        java.util.List<String> lineasArchivo = new java.util.ArrayList<>();
        boolean encontrado = false;

        if (archivo.exists()) {
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                        // Rescatamos los datos y forzamos el estado a 0
                        String n = datos.length > 1 ? datos[1].trim() : "";
                        String a = datos.length > 2 ? datos[2].trim() : "";
                        String t = datos.length > 3 ? datos[3].trim() : "";
                        String c = datos.length > 4 ? datos[4].trim() : "";
                        lineasArchivo.add(idStr + "," + n + "," + a + "," + t + "," + c + ",0");
                        encontrado = true;
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo: " + e.getMessage());
                return;
            }
        }

        if (encontrado) {
            try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter(archivo))) {
                for (String l : lineasArchivo) {
                    pw.println(l);
                }
                JOptionPane.showMessageDialog(this, "Entrenador eliminado lógicamente.");
                limpiarCampos();
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String idStr = txtId.getText().trim();
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellido.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String correo = txtCorreo.getText().trim();

        // 1. Validar campos obligatorios (los que tienen asterisco en la imagen)
        if (idStr.isEmpty() || nombre.isEmpty() || apellido.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Los campos ID, Nombre y Apellido son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Validar el formato del teléfono (Formato República Dominicana: 10 dígitos)
        if (!telefono.isEmpty()) {
            // Eliminamos espacios y guiones para contar solo los números puros
            String numerosTelefono = telefono.replaceAll("[\\s-]", "");

            // Verificamos que solo sean números y que la longitud sea exactamente 10
            if (!numerosTelefono.matches("\\d+") || numerosTelefono.length() != 10) {
                JOptionPane.showMessageDialog(this, "El número de teléfono debe tener exactamente 10 dígitos.\nEjemplo válido: 829-035-3412", "Formato de Teléfono Incorrecto", JOptionPane.WARNING_MESSAGE);
                txtTelefono.requestFocus();
                return;
            }

            // (Opcional pero recomendado) Formateamos el texto automáticamente para guardarlo con los guiones
            // aunque el usuario lo haya escrito todo junto, ej: "8290353412" -> "829-035-3412"
            telefono = numerosTelefono.substring(0, 3) + "-" + numerosTelefono.substring(3, 6) + "-" + numerosTelefono.substring(6, 10);
        }

        // 2. Validar correo si el usuario escribió algo (igual que en usuarios)
        if (!correo.isEmpty()) {
            String regexCorreo = "^[a-zA-Z0-9_+&*-]+(?:\\.[a-zA-Z0-9_+&*-]+)*@(?:[a-zA-Z0-9-]+\\.)+[a-zA-Z]{2,7}$";
            if (!correo.matches(regexCorreo)) {
                JOptionPane.showMessageDialog(this, "El formato del correo es inválido.", "Formato Incorrecto", JOptionPane.WARNING_MESSAGE);
                txtCorreo.requestFocus();
                return;
            }
        }

        java.io.File archivo = new java.io.File("entrenadores.txt");
        java.util.List<String> lineasArchivo = new java.util.ArrayList<>();

        if (archivo.exists()) {
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                        if (!esNuevoEntrenador) {
                            // Actualiza y mantiene el estado 1 (Activo)
                            lineasArchivo.add(idStr + "," + nombre + "," + apellido + "," + telefono + "," + correo + ",1");
                        }
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo: " + e.getMessage());
            }
        }

        if (esNuevoEntrenador) {
            // Evitar duplicados
            for (String l : lineasArchivo) {
                String[] datos = l.split(",", -1);
                if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                    JOptionPane.showMessageDialog(this, "El ID de entrenador ya existe.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
            // Agrega nuevo con estado 1
            lineasArchivo.add(idStr + "," + nombre + "," + apellido + "," + telefono + "," + correo + ",1");
        }

        try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter(archivo))) {
            for (String l : lineasArchivo) {
                pw.println(l);
            }
            JOptionPane.showMessageDialog(this, "Datos guardados correctamente.");
            limpiarCampos();
        } catch (java.io.IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

