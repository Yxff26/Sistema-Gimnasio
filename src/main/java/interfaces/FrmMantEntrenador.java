    private void txtIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdActionPerformed
        String idStr = txtId.getText().trim();
        if (idStr.isEmpty()) {
            setCamposHabilitados(false);
            return;
        }

        // Validar que sea un entero válido
        try {
            Integer.parseInt(idStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID del Entrenador debe ser un número entero.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtId.setText("");
            setCamposHabilitados(false);
            txtId.requestFocus();
            return;
        }

        java.io.File archivo = new java.io.File("entrenadores.txt");
        boolean encontrado = false;
        String nombre = "", apellido = "", telefono = "", correo = "", estado = "1";

        if (archivo.exists()) {
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length >= 3 && datos[0].trim().equals(idStr)) {
                        encontrado = true;
                        nombre = datos[1].trim();
                        apellido = datos[2].trim();
                        telefono = datos.length > 3 ? datos[3].trim() : "";
                        correo = datos.length > 4 ? datos[4].trim() : "";
                        estado = datos.length > 5 ? datos[5].trim() : "1";
                        break;
                    }
                }
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al buscar el entrenador: " + e.getMessage());
            }
        }

        if (!encontrado) {
            JOptionPane.showMessageDialog(this, "El entrenador es NUEVO y se está creando.", "Aviso", JOptionPane.INFORMATION_MESSAGE);
            esNuevoEntrenador = true;

            // Habilitar campos de texto y botones para nuevo registro
            setCamposHabilitados(true);
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(false);

            txtNombre.requestFocus();
        } else {
            if (estado.equals("0")) {
                JOptionPane.showMessageDialog(this, "Este entrenador se encuentra ELIMINADO/INACTIVO.\nNo es posible modificarlo.", "Inactivo", JOptionPane.ERROR_MESSAGE);
                limpiarCampos();
                return;
            }

            JOptionPane.showMessageDialog(this, "El entrenador ya EXISTE y se está modificando.", "Aviso", JOptionPane.WARNING_MESSAGE);
            esNuevoEntrenador = false;

            txtNombre.setText(nombre);
            txtApellido.setText(apellido);
            txtTelefono.setText(telefono);
            txtCorreo.setText(correo);

            // Habilitar campos de texto y todos los botones para edición
            setCamposHabilitados(true);
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(true);

            txtNombre.requestFocus();
        }
    }//GEN-LAST:event_txtIdActionPerformed

