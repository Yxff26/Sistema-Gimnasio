    private void formatearHoraAutomatica() {
        String hora = txtHoraAct.getText().trim();
        if (hora.matches("\\d{4}")) {
            txtHoraAct.setText(hora.substring(0, 2) + ":" + hora.substring(2, 4));
        }
    }
    
    private String idHorarioStr_Inactivo_Helper(String idStr, String dia, String hora, String idAct) {
        return idStr + "," + dia + "," + hora + "," + idAct + ",0";
    }
    
