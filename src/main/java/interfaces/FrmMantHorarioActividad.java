    private void txtIdActividadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdActividadActionPerformed
        String idActStr = txtIdActividad.getText().trim();
        if (idActStr.isEmpty()) return;

        try {
            Integer.parseInt(idActStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de Actividad debe ser un número entero.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtIdActividad.setText("");
            txtIdActividad.requestFocus();
            return;
        }

        File archivoActividades = new File("actividades.txt");
        boolean actividadExiste = false;

        if (archivoActividades.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivoActividades))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idActStr)) {
                        String estadoAct = datos.length > 5 ? datos[5].trim() : "1";
                        if (estadoAct.equals("1")) {
                            actividadExiste = true;
                            break;
                        }
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al verificar la actividad: " + e.getMessage());
            }
        }

        if (!actividadExiste) {
            JOptionPane.showMessageDialog(this, "El ID de Actividad ingresado NO existe o se encuentra inactivo.", "Error de Referencia", JOptionPane.ERROR_MESSAGE);
            txtIdActividad.setText("");
            txtIdActividad.requestFocus();
        } else {
            btnGuardar.requestFocus();
        }
    }//GEN-LAST:event_txtIdActividadActionPerformed

    private void txtIdHorarioActActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdHorarioActActionPerformed
        String idStr = txtIdHorarioAct.getText().trim();
        if (idStr.isEmpty()) {
            setCamposHabilitados(false);
            return;
        }

        File archivo = new File("horarios_actividades.txt");
        boolean encontrado = false;
        String dia = "", hora = "", idAct = "", estado = "1";

        if (archivo.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    // Estructura: Id_Horario_Act, Dia_Act, Hora_Act, Id_Actividad, Estado
                    if (datos.length >= 4 && datos[0].trim().equals(idStr)) {
                        encontrado = true;
                        dia = datos[1].trim();
                        hora = datos[2].trim();
                        idAct = datos[3].trim();
                        estado = datos.length > 4 ? datos[4].trim() : "1";
                        break;
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al buscar el horario de actividad: " + e.getMessage());
            }
        }

        if (!encontrado) {
            JOptionPane.showMessageDialog(this, "Creando...", "Aviso", JOptionPane.INFORMATION_MESSAGE);
            esNuevoHorario = true;

            // Habilitar campos y botones para nuevo registro
            setCamposHabilitados(true);
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(false);

            cmbDiaAct.requestFocus();
        } else {
            if (estado.equals("0")) {
                JOptionPane.showMessageDialog(this, "Este horario de actividad se encuentra ELIMINADO/INACTIVO.\nNo es posible modificarlo.", "Inactivo", JOptionPane.ERROR_MESSAGE);
                limpiarCampos();
                return;
            }

            JOptionPane.showMessageDialog(this, "Modificando...", "Aviso", JOptionPane.WARNING_MESSAGE);
            esNuevoHorario = false;

            cmbDiaAct.setSelectedItem(dia);
            txtHoraAct.setText(hora);
            txtIdActividad.setText(idAct);

            // Habilitar campos y botones para modificación
            setCamposHabilitados(true);
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(true);

            cmbDiaAct.requestFocus();
        }
    }//GEN-LAST:event_txtIdHorarioActActionPerformed

