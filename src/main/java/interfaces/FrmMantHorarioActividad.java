    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String idHorarioStr = txtIdHorarioAct.getText().trim();
        String dia = cmbDiaAct.getSelectedItem().toString();
        
        // Aplicar formato automático a la hora antes de validar
        formatearHoraAutomatica();
        String horaStr = txtHoraAct.getText().trim();
        
        String idActStr = txtIdActividad.getText().trim();

        // 1. Validar atributos obligatorios
        if (idHorarioStr.isEmpty() || horaStr.isEmpty() || idActStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Validar formato de hora estricto tipo 00:00 (HH:mm de 24 horas)
        String patronHora = "^([0-1]?[0-9]|2[0-3]):[0-5][0-9]$";
        if (!horaStr.matches(patronHora)) {
            JOptionPane.showMessageDialog(this, "La hora debe cumplir con el formato HH:mm (ej. 08:00 o 14:30) y estar en el rango de 00:00 a 23:59.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtHoraAct.requestFocus();
            return;
        }

        try {
            Integer.parseInt(idActStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de Actividad debe ser un número entero válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtIdActividad.requestFocus();
            return;
        }

        // 2. VALIDAR QUE EL ID DE ACTIVIDAD EXISTA Y ESTÉ ACTIVO
        File archivoActividades = new File("actividades.txt");
        boolean actividadExiste = false;

        if (archivoActividades.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivoActividades))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idActStr)) {
                        String estadoAct = datos.length > 5 ? datos[5].trim() : "1";
                        if (estadoAct.equals("1")) {
                            actividadExiste = true;
                            break;
                        }
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al verificar la actividad: " + e.getMessage());
                return;
            }
        }

        if (!actividadExiste) {
            JOptionPane.showMessageDialog(this, "El ID de Actividad especificado NO existe o se encuentra inactivo.", "Error de Referencia", JOptionPane.ERROR_MESSAGE);
            txtIdActividad.requestFocus();
            return;
        }

        // 3. Guardar en horarios_actividades.txt
        File archivo = new File("horarios_actividades.txt");
        List<String> lineasArchivo = new ArrayList<>();

        if (archivo.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idHorarioStr)) {
                        if (!esNuevoHorario) {
                            // Actualiza manteniendo el estado activo (1)
                            lineasArchivo.add(idHorarioStr + "," + dia + "," + horaStr + "," + idActStr + ",1");
                        }
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo de horarios de actividades: " + e.getMessage());
            }
        }

        if (esNuevoHorario) {
            for (String l : lineasArchivo) {
                String[] datos = l.split(",", -1);
                if (datos.length > 0 && datos[0].trim().equals(idHorarioStr)) {
                    JOptionPane.showMessageDialog(this, "El ID de este horario ya existe.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
            // Agrega nuevo horario con estado activo (1)
            lineasArchivo.add(idHorarioStr + "," + dia + "," + horaStr + "," + idActStr + ",1");
        }

        try (PrintWriter pw = new PrintWriter(new FileWriter(archivo))) {
            for (String l : lineasArchivo) {
                pw.println(l);
            }
            JOptionPane.showMessageDialog(this, "Horario de actividad guardado correctamente.");
            limpiarCampos();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar horario de actividad: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String idStr = txtIdHorarioAct.getText().trim();
        if (idStr.isEmpty()) return;

        int confirm = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar el horario de actividad ID: " + idStr + "?", "Confirmar", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        File archivo = new File("horarios_actividades.txt");
        List<String> lineasArchivo = new ArrayList<>();
        boolean encontrado = false;

        if (archivo.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                        String dia = datos.length > 1 ? datos[1].trim() : "";
                        String hora = datos.length > 2 ? datos[2].trim() : "";
                        String idAct = datos.length > 3 ? datos[3].trim() : "";
                        // Cambiar estado a inactivo (0)
                        lineasArchivo.add(idHorarioStr_Inactivo_Helper(idStr, dia, hora, idAct));
                        encontrado = true;
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo: " + e.getMessage());
                return;
            }
        }

        if (encontrado) {
            try (PrintWriter pw = new PrintWriter(new FileWriter(archivo))) {
                for (String l : lineasArchivo) {
                    pw.println(l);
                }
                JOptionPane.showMessageDialog(this, "Horario de actividad eliminado lógicamente.");
                limpiarCampos();
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

