    private void txtIdLocalizacionActActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdLocalizacionActActionPerformed
        String idLocStr = txtIdLocalizacionAct.getText().trim();
        if (idLocStr.isEmpty()) return;

        try {
            Integer.parseInt(idLocStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de Localización debe ser un número entero.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtIdLocalizacionAct.setText("");
            txtIdLocalizacionAct.requestFocus();
            return;
        }

        File archivoLocalizaciones = new File("localizaciones.txt");
        boolean localizacionExiste = false;

        if (archivoLocalizaciones.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivoLocalizaciones))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idLocStr)) {
                        String estadoLoc = datos.length > 2 ? datos[2].trim() : "1";
                        if (estadoLoc.equals("1")) {
                            localizacionExiste = true;
                            break;
                        }
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al verificar la localización: " + e.getMessage());
            }
        }

        if (!localizacionExiste) {
            JOptionPane.showMessageDialog(this, "El ID de Localización ingresado NO existe o se encuentra inactivo.", "Error de Referencia", JOptionPane.ERROR_MESSAGE);
            txtIdLocalizacionAct.setText("");
            txtIdLocalizacionAct.requestFocus();
        } else {
            txtIdEntrenadorAct.requestFocus();
        }
    }//GEN-LAST:event_txtIdLocalizacionActActionPerformed

    private void txtIdActActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdActActionPerformed
        String idStr = txtIdAct.getText().trim();
        if (idStr.isEmpty()) return;

        // Validar que el ID sea un número entero
        try {
            Integer.parseInt(idStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de la Actividad debe ser un número entero.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtIdAct.setText("");
            txtIdAct.requestFocus();
            return;
        }

        File archivo = new File("actividades.txt");
        boolean encontrado = false;
        String nombre = "", descripcion = "", idLocalizacion = "", idEntrenador = "", estado = "1";

        if (archivo.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    // Estructura: Id_Act, Nombre_Act, Descripcion_Act, Id_Localizacion_Act, Id_Entrenador_Act, Estado
                    if (datos.length >= 5 && datos[0].trim().equals(idStr)) {
                        encontrado = true;
                        nombre = datos[1].trim();
                        descripcion = datos[2].trim();
                        idLocalizacion = datos[3].trim();
                        idEntrenador = datos[4].trim();
                        estado = datos.length > 5 ? datos[5].trim() : "1";
                        break;
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al buscar la actividad: " + e.getMessage());
            }
        }

        if (!encontrado) {
            JOptionPane.showMessageDialog(this, "Creando...", "Aviso", JOptionPane.INFORMATION_MESSAGE);
            esNuevaActividad = true;
            
            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(false);
            
            txtNombreAct.requestFocus();
        } else {
            if (estado.equals("0")) {
                JOptionPane.showMessageDialog(this, "Esta actividad se encuentra ELIMINADA/INACTIVA.\nNo es posible modificarla.", "Inactivo", JOptionPane.ERROR_MESSAGE);
                limpiarCampos();
                return;
            }

            JOptionPane.showMessageDialog(this, "Modificando...", "Aviso", JOptionPane.WARNING_MESSAGE);
            esNuevaActividad = false;
            
            txtNombreAct.setText(nombre);
            txtDescripcionAct.setText(descripcion);
            txtIdLocalizacionAct.setText(idLocalizacion);
            txtIdEntrenadorAct.setText(idEntrenador);

            btnGuardar.setEnabled(true);
            btnLimpiarCampos.setEnabled(true);
            btnEliminar.setEnabled(true);
            
            txtNombreAct.requestFocus();
        }
    }//GEN-LAST:event_txtIdActActionPerformed

