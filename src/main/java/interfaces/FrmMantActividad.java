    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String idStr = txtIdAct.getText().trim();
        String nombre = txtNombreAct.getText().trim();
        String descripcion = txtDescripcionAct.getText().trim();
        String idLocStr = txtIdLocalizacionAct.getText().trim();
        String idEntStr = txtIdEntrenadorAct.getText().trim();

        // 1. Validar atributos obligatorios
        if (idStr.isEmpty() || nombre.isEmpty() || descripcion.isEmpty() || idLocStr.isEmpty() || idEntStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Integer.parseInt(idLocStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de Localización debe ser un número entero válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtIdLocalizacionAct.requestFocus();
            return;
        }

        try {
            Integer.parseInt(idEntStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de Entrenador debe ser un número entero válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtIdEntrenadorAct.requestFocus();
            return;
        }

        // 2. VALIDAR QUE EL ID DE LOCALIZACIÓN EXISTA Y ESTÉ ACTIVO
        File archivoLocalizaciones = new File("localizaciones.txt");
        boolean localizacionExiste = false;

        if (archivoLocalizaciones.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivoLocalizaciones))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idLocStr)) {
                        String estadoLoc = datos.length > 2 ? datos[2].trim() : "1";
                        if (estadoLoc.equals("1")) {
                            localizacionExiste = true;
                            break;
                        }
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al verificar la localización: " + e.getMessage());
                return;
            }
        }

        if (!localizacionExiste) {
            JOptionPane.showMessageDialog(this, "El ID de Localización especificado NO existe o se encuentra inactivo.", "Error de Referencia", JOptionPane.ERROR_MESSAGE);
            txtIdLocalizacionAct.requestFocus();
            return;
        }

        // 3. VALIDAR QUE EL ID DE ENTRENADOR EXISTA Y ESTÉ ACTIVO
        File archivoEntrenadores = new File("entrenadores.txt");
        boolean entrenadorExiste = false;

        if (archivoEntrenadores.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivoEntrenadores))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idEntStr)) {
                        String estadoEnt = datos.length > 0 ? datos[datos.length - 1].trim() : "1";
                        if (estadoEnt.equals("1")) {
                            entrenadorExiste = true;
                            break;
                        }
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al verificar el entrenador: " + e.getMessage());
                return;
            }
        }

        if (!entrenadorExiste) {
            JOptionPane.showMessageDialog(this, "El ID de Entrenador especificado NO existe o se encuentra inactivo.", "Error de Referencia", JOptionPane.ERROR_MESSAGE);
            txtIdEntrenadorAct.requestFocus();
            return;
        }

        // 4. Guardar en actividades.txt
        File archivo = new File("actividades.txt");
        List<String> lineasArchivo = new ArrayList<>();

        if (archivo.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                        if (!esNuevaActividad) {
                            // Actualiza manteniendo el estado activo (1)
                            lineasArchivo.add(idStr + "," + nombre + "," + descripcion + "," + idLocStr + "," + idEntStr + ",1");
                        }
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo de actividades: " + e.getMessage());
            }
        }

        if (esNuevaActividad) {
            for (String l : lineasArchivo) {
                String[] datos = l.split(",", -1);
                if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                    JOptionPane.showMessageDialog(this, "El ID de esta actividad ya existe.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
            // Agrega nueva actividad con estado activo (1)
            lineasArchivo.add(idStr + "," + nombre + "," + descripcion + "," + idLocStr + "," + idEntStr + ",1");
        }

        try (PrintWriter pw = new PrintWriter(new FileWriter(archivo))) {
            for (String l : lineasArchivo) {
                pw.println(l);
            }
            JOptionPane.showMessageDialog(this, "Actividad guardada correctamente.");
            limpiarCampos();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar actividad: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String idStr = txtIdAct.getText().trim();
        if (idStr.isEmpty()) return;

        int confirm = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar la actividad ID: " + idStr + "?", "Confirmar", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        File archivo = new File("actividades.txt");
        List<String> lineasArchivo = new ArrayList<>();
        boolean encontrado = false;

        if (archivo.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
                String linea;
                while ((linea = br.readLine()) != null) {
                    String[] datos = linea.split(",", -1);
                    if (datos.length > 0 && datos[0].trim().equals(idStr)) {
                        String nom = datos.length > 1 ? datos[1].trim() : "";
                        String desc = datos.length > 2 ? datos[2].trim() : "";
                        String idLoc = datos.length > 3 ? datos[3].trim() : "";
                        String idEnt = datos.length > 4 ? datos[4].trim() : "";
                        // Cambiar estado a inactivo (0)
                        lineasArchivo.add(idStr + "," + nom + "," + desc + "," + idLoc + "," + idEnt + ",0");
                        encontrado = true;
                    } else {
                        lineasArchivo.add(linea);
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer archivo: " + e.getMessage());
                return;
            }
        }

        if (encontrado) {
            try (PrintWriter pw = new PrintWriter(new FileWriter(archivo))) {
                for (String l : lineasArchivo) {
                    pw.println(l);
                }
                JOptionPane.showMessageDialog(this, "Actividad eliminada lógicamente.");
                limpiarCampos();
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

