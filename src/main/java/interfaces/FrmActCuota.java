    // Método auxiliar para leer un archivo y devolver una lista de líneas
    private java.util.List<String> leerArchivo(java.io.File archivo) throws java.io.IOException {
        java.util.List<String> lineas = new java.util.ArrayList<>();
        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                lineas.add(linea);
            }
        }
        return lineas;
    }

    // Método auxiliar para sobreescribir un archivo con una lista actualizada
    private void escribirArchivo(java.io.File archivo, java.util.List<String> lineas) throws java.io.IOException {
        try (java.io.BufferedWriter bw = new java.io.BufferedWriter(new java.io.FileWriter(archivo, false))) { // false para sobreescribir
            for (String linea : lineas) {
                bw.write(linea);
                bw.newLine();
            }
        }
    }

