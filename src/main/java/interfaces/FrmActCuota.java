    private void btnProcesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcesarActionPerformed
        java.util.Date utilFechaInicial = dateFechaInicial.getDate();
        java.util.Date utilFechaFinal = dateFechaFinal.getDate();

        if (utilFechaInicial == null || utilFechaFinal == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar ambas fechas.", "Validación", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Formateador para comparar fechas y leer los archivos
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd/MM/yyyy");

        try {
            // Cargar todos los archivos en memoria para actualizarlos
            java.io.File fEncabezado = new java.io.File("encabezado_cuota.txt");
            java.io.File fDetalle = new java.io.File("detalle_cuota.txt");
            java.io.File fCobros = new java.io.File("cobros.txt");
            java.io.File fClientes = new java.io.File("clientes.txt");

            if (!fEncabezado.exists() || !fCobros.exists() || !fClientes.exists()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Faltan archivos de datos para procesar.");
                return;
            }

            // Listas para almacenar las líneas y luego reescribir los archivos
            java.util.List<String> listEncabezados = leerArchivo(fEncabezado);
            java.util.List<String> listDetalles = fDetalle.exists() ? leerArchivo(fDetalle) : new java.util.ArrayList<>();
            java.util.List<String> listCobros = leerArchivo(fCobros);
            java.util.List<String> listClientes = leerArchivo(fClientes);

            int cuotasProcesadas = 0;

            // Recorrer los encabezados de cuota
            for (int i = 0; i < listEncabezados.size(); i++) {
                String[] datosEnc = listEncabezados.get(i).split(",", -1);
                if (datosEnc.length < 5) continue;

                String idCuota = datosEnc[0].trim();
                java.util.Date fechaCuota = sdf.parse(datosEnc[1].trim());
                String idCliente = datosEnc[2].trim();
                double totalPagadoCuota = Double.parseDouble(datosEnc[3].trim());
                boolean statusCuota = Boolean.parseBoolean(datosEnc[4].trim());

                // ====================================================================
                // REQUISITO IX: Validar rango de fechas y que Status_Cuota sea false
                // ====================================================================
                boolean enRango = !fechaCuota.before(utilFechaInicial) && !fechaCuota.after(utilFechaFinal);

                if (!statusCuota && enRango) {

                    // ====================================================================
                    // REQUISITO X (Parte 1): Actualizar el Valor_Cobro en el archivo de Cobro
                    // ====================================================================
                    for (String lineaDetalle : listDetalles) {
                        String[] datosDet = lineaDetalle.split(",", -1);
                        if (datosDet[0].trim().equals(idCuota)) {
                            double valorAbonado = Double.parseDouble(datosDet[3].trim());
                            String idCobro = datosDet[4].trim();

                            // Buscar este cobro en listCobros y rebajarle el valor
                            for (int c = 0; c < listCobros.size(); c++) {
                                String[] datosCobro = listCobros.get(c).split(",", -1);
                                if (datosCobro[0].trim().equals(idCobro)) {
                                    double valorActualCobro = Double.parseDouble(datosCobro[3].trim());
                                    valorActualCobro -= valorAbonado;
                                    boolean statusCobro = Boolean.parseBoolean(datosCobro[5].trim());

                                    // "Si el Valor_Cobro queda en Cero se cambia el Status_Cobro a true"
                                    if (valorActualCobro <= 0) {
                                        valorActualCobro = 0;
                                        statusCobro = true;
                                    }

                                    datosCobro[3] = String.valueOf(valorActualCobro);
                                    datosCobro[5] = String.valueOf(statusCobro);
                                    listCobros.set(c, String.join(",", datosCobro));
                                    break; // Ya actualizamos el cobro, pasamos al siguiente detalle
                                }
                            }
                        }
                    }

                    // ====================================================================
                    // REQUISITO X (Parte 2): Actualizar los balances de los clientes
                    // ====================================================================
                    for (int cli = 0; cli < listClientes.size(); cli++) {
                        String[] datosCli = listClientes.get(cli).split(",", -1);
                        if (datosCli[0].trim().equals(idCliente)) {
                            double balanceActual = Double.parseDouble(datosCli[12].trim());
                            balanceActual -= totalPagadoCuota; // Rebajamos lo que pagó
                            if(balanceActual < 0) balanceActual = 0;

                            datosCli[12] = String.valueOf(balanceActual);
                            listClientes.set(cli, String.join(",", datosCli));
                            break; // Ya actualizamos el cliente
                        }
                    }

                    // ====================================================================
                    // REQUISITO XI: Cambiar Status_Cuota a true porque ya se aplicó
                    // ====================================================================
                    datosEnc[4] = "true";
                    listEncabezados.set(i, String.join(",", datosEnc));
                    cuotasProcesadas++;
                }
            }

            if (cuotasProcesadas == 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "No se encontraron cuotas pendientes para actualizar en este rango de fechas.", "Información", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                return;
            }

            // Guardar todos los cambios en sus respectivos archivos
            escribirArchivo(fEncabezado, listEncabezados);
            escribirArchivo(fCobros, listCobros);
            escribirArchivo(fClientes, listClientes);

            javax.swing.JOptionPane.showMessageDialog(this, "Proceso finalizado. Se actualizaron " + cuotasProcesadas + " cuotas exitosamente.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);

            dateFechaInicial.setDate(null);
            dateFechaFinal.setDate(null);

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error durante el procesamiento: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnProcesarActionPerformed

